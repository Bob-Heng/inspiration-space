const LangContext = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(
    () => localStorage.getItem(STORAGE_KEY) || 'zh',
  )
  function setLang(next) {
    localStorage.setItem(STORAGE_KEY, next)
    setLangState(next)
  }
  function t(key) {
    const val = STRINGS[lang]?.[key] ?? STRINGS.zh[key]
    return val ?? key
  }
  // 带占位替换：tf('totalItems', {n: 3})
  function tf(key, vars = {}) {
    let s = t(key)
    if (typeof s !== 'string') return key
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }
  return (
    <LangContext.Provider value={{ lang, setLang, t, tf }}>
      {children}
    </LangContext.Provider>
  )
}

export function useLang() {
  return useContext(LangContext)
}

/** 语言切换下拉（登录页与首页顶部共用），带「语言/Language」说明 */
export function LangSelect({ className = '' }) {
  const { lang, setLang } = useLang()
  return (
    <label className={`flex items-center gap-1.5 text-sm text-slate-500 ${className}`}>
      <span>语言/Language</span>
      <select
        aria-label="语言 / Language"
        className="rounded border border-slate-300 bg-white px-2 py-1 text-sm text-slate-600"
        value={lang}
        onChange={(e) => setLang(e.target.value)}
      >
        <option value="zh">中文</option>
        <option value="en">English</option>
      </select>
    </label>
  )
}
